"""PostgreSQL storage (psycopg 3 + a small connection pool). Rows come back as dicts."""
import json
import threading
from contextlib import contextmanager
from datetime import datetime, timezone

from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool

from . import config

# ponytail: JSON stays in TEXT columns and timestamps are ISO-8601 TEXT, exactly as in the SQLite days, so the
# code (json.loads / db.dumps / string dates) did not change. Move to JSONB / timestamptz when we query inside them.
# Integer ids are IDENTITY "BY DEFAULT" so `cqa.cli migrate-sqlite` can copy the old ids as they are.
SCHEMA = """
CREATE TABLE IF NOT EXISTS conversations (
    id TEXT PRIMARY KEY, group_id TEXT, channel TEXT, language TEXT, audio_url TEXT,
    transcript_hash TEXT, raw_json TEXT, imported_at TEXT);
CREATE TABLE IF NOT EXISTS messages (
    conversation_id TEXT, idx INTEGER, mid TEXT, speaker TEXT, ts_raw TEXT, t_sec DOUBLE PRECISION,
    text TEXT, text_masked TEXT, lang TEXT, PRIMARY KEY (conversation_id, idx));
CREATE TABLE IF NOT EXISTS checklists (
    version INTEGER PRIMARY KEY, json TEXT NOT NULL, note TEXT, created_by TEXT, created_at TEXT);
CREATE TABLE IF NOT EXISTS evaluations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, conversation_id TEXT, checklist_version INTEGER,
    status TEXT, total_ai DOUBLE PRECISION, total DOUBLE PRECISION, gross_error INTEGER, models TEXT,
    prompt_version TEXT, tokens_in INTEGER, tokens_out INTEGER, cost_usd DOUBLE PRECISION, result_json TEXT,
    created_at TEXT);
CREATE TABLE IF NOT EXISTS appeals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, evaluation_id INTEGER, criterion_id TEXT,
    comment TEXT, filed_by TEXT, state TEXT, reason TEXT, decided_by TEXT, created_at TEXT, decided_at TEXT);
CREATE TABLE IF NOT EXISTS audit (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at TEXT, who TEXT, entity TEXT, entity_id TEXT,
    action TEXT, before TEXT, after TEXT, reason TEXT);
CREATE TABLE IF NOT EXISTS cache (key TEXT PRIMARY KEY, value TEXT, created_at TEXT);
CREATE TABLE IF NOT EXISTS traces (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, conversation_id TEXT, role TEXT, attempt INTEGER,
    provider TEXT, model TEXT, criteria TEXT, request TEXT, response TEXT, error TEXT,
    validation TEXT, tokens_in INTEGER, tokens_out INTEGER, latency_ms INTEGER, created_at TEXT);
CREATE TABLE IF NOT EXISTS gold_labels (
    conversation_id TEXT, criterion_id TEXT, label TEXT, fingerprint TEXT, note TEXT, labelled_by TEXT, at TEXT,
    PRIMARY KEY (conversation_id, criterion_id));
CREATE TABLE IF NOT EXISTS stress_tests (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, conversation_id TEXT, mutation TEXT, result_json TEXT,
    created_at TEXT);
CREATE INDEX IF NOT EXISTS ix_eval_conv ON evaluations (conversation_id);
CREATE INDEX IF NOT EXISTS ix_trace_conv ON traces (conversation_id);
"""
TABLES = ("conversations", "messages", "checklists", "evaluations", "appeals", "audit", "cache", "traces",
          "gold_labels")
IDENTITY_TABLES = ("evaluations", "appeals", "audit", "traces")


_pools: dict[str, ConnectionPool] = {}  # by URL, so tests can point config.DATABASE_URL at another schema
_lock = threading.Lock()


def _pool() -> ConnectionPool:
    url = config.DATABASE_URL
    with _lock:
        if url not in _pools:
            # A fresh connection costs ~12 ms (auth + backend start); evaluations make dozens of short queries.
            _pools[url] = ConnectionPool(url, kwargs={"row_factory": dict_row}, min_size=1, max_size=10,
                                         check=ConnectionPool.check_connection, open=True)
        return _pools[url]


def close() -> None:
    with _lock:
        for pool in _pools.values():
            pool.close()
        _pools.clear()


@contextmanager
def tx():
    """A transaction on a pooled connection: commits on success, rolls back on error."""
    with _pool().connection() as con:
        yield con


def init() -> None:
    with tx() as con:
        con.execute("SELECT pg_advisory_xact_lock(4242)")  # app and CLI may start at the same time
        con.execute(SCHEMA)


def rows(sql: str, *args) -> list[dict]:
    with tx() as con:
        return con.execute(sql, args).fetchall()


def row(sql: str, *args) -> dict | None:
    found = rows(sql, *args)
    return found[0] if found else None


def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def dumps(obj) -> str:
    return json.dumps(obj, ensure_ascii=False)


def audit(con, who, entity, entity_id, action, before=None, after=None, reason=None) -> None:
    """Every change to appeals, verdicts and checklists writes one line here."""
    con.execute(
        "INSERT INTO audit (at, who, entity, entity_id, action, before, after, reason) VALUES (%s,%s,%s,%s,%s,%s,%s,%s)",
        (now(), who, entity, str(entity_id), action,
         None if before is None else dumps(before), None if after is None else dumps(after), reason),
    )
